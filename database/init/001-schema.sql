CREATE TABLE vehicles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plate varchar(12) NOT NULL UNIQUE,
  owner varchar(100) NOT NULL CHECK (length(trim(owner)) > 0),
  kind varchar(20) NOT NULL CHECK (kind IN ('Automóvil', 'Motocicleta', 'Pickup', 'Otro')),
  color varchar(40) NOT NULL
);
CREATE TABLE tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id integer NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
  entry_at timestamptz NOT NULL,
  exit_at timestamptz,
  hourly_rate numeric(8,2) NOT NULL CONSTRAINT positive_rate CHECK (hourly_rate > 0),
  CONSTRAINT valid_dates CHECK (exit_at IS NULL OR exit_at >= entry_at)
);
CREATE INDEX ix_tickets_vehicle_id ON tickets(vehicle_id);
CREATE UNIQUE INDEX one_active_ticket_per_vehicle ON tickets(vehicle_id) WHERE exit_at IS NULL;
